#!/usr/bin/env python3
"""Generate WebP variants and record intrinsic sizes for the project images.

For every JPEG under public/projects and public/case it writes:

  <name>-720.webp     720px wide, for phones and the two-up galleries
  <name>-<width>.webp native width, so dense screens get a sharp file

and rewrites lib/image-sizes.ts, which components use for width/height (no
layout shift) and for the srcset the pages emit. The original JPEGs stay as the
fallback for anything that cannot decode WebP.

Usage:
    python3 scripts/optimize-images.py

Requires Pillow.
"""

import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, 'lib', 'image-sizes.ts')
DIRECTORIES = ('projects', 'case')
PAGE_WIDTH = 720
QUALITY = 80


def collect():
    entries = {}
    for sub in DIRECTORIES:
        directory = os.path.join(ROOT, 'public', sub)
        if not os.path.isdir(directory):
            continue
        for name in sorted(os.listdir(directory)):
            if not name.lower().endswith(('.jpg', '.jpeg', '.png')):
                continue
            entries[f'/{sub}/{name}'] = os.path.join(directory, name)
    return entries


def variants(path):
    stem = os.path.splitext(os.path.basename(path))[0]
    directory = os.path.dirname(path)
    image = Image.open(path).convert('RGB')
    widths = sorted({w for w in (PAGE_WIDTH, image.width) if w <= image.width})
    written = 0

    for width in widths:
        target = os.path.join(directory, f'{stem}-{width}.webp')
        if width == image.width:
            resized = image
        else:
            height = round(image.height * width / image.width)
            resized = image.resize((width, height), Image.LANCZOS)
        resized.save(target, 'WEBP', quality=QUALITY, method=6)
        written += 1

    return image.size, written, sum(os.path.getsize(os.path.join(directory, f'{stem}-{w}.webp')) for w in widths)


def write_manifest(sizes):
    lines = [
        '/** Generated by `npm run images` — do not edit by hand. */',
        'export const imageSizes: Record<string, [number, number]> = {',
    ]
    for src in sorted(sizes):
        width, height = sizes[src]
        lines.append(f"  '{src}': [{width}, {height}],")
    lines.append('}')
    lines.append('')
    with open(MANIFEST, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))


def main():
    entries = collect()
    if not entries:
        sys.exit('no images found under public/projects or public/case')

    sizes = {}
    files = 0
    total = 0
    for src, path in entries.items():
        size, written, size_bytes = variants(path)
        sizes[src] = size
        files += written
        total += size_bytes

    write_manifest(sizes)
    print(f'{len(entries)} sources -> {files} WebP files, {total // 1024} KB total')
    print(f'wrote {os.path.relpath(MANIFEST, ROOT)}')


if __name__ == '__main__':
    main()
