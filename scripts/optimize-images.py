#!/usr/bin/env python3
"""Generate AVIF/WebP variants, dominant colours and intrinsic sizes.

For every JPEG or PNG under public/projects and public/case it writes:

  <name>-720.avif      and <name>-720.webp      720px wide, for phones
  <name>-<width>.avif  and <name>-<width>.webp  native width, for dense screens

plus two generated manifests:

  lib/image-sizes.ts    intrinsic width/height, so the browser reserves space
  lib/image-colors.ts   one average colour per image, painted behind the
                        picture while it loads

The original JPEGs stay as the fallback for anything that cannot decode either
modern format.

Usage:
    python3 scripts/optimize-images.py

Requires Pillow with AVIF support (`python3 -c "from PIL import features;
print(features.check('avif'))"`).
"""

import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SIZES = os.path.join(ROOT, 'lib', 'image-sizes.ts')
COLORS = os.path.join(ROOT, 'lib', 'image-colors.ts')
DIRECTORIES = ('projects', 'case')
PAGE_WIDTH = 720
FORMATS = (
    ('avif', 'AVIF', {'quality': 60, 'speed': 6}),
    ('webp', 'WEBP', {'quality': 80, 'method': 6}),
)


def collect():
    entries = {}
    for sub in DIRECTORIES:
        directory = os.path.join(ROOT, 'public', sub)
        if not os.path.isdir(directory):
            continue
        for name in sorted(os.listdir(directory)):
            if not name.lower().endswith(('.jpg', '.jpeg', '.png')):
                continue
            entries[f'/{sub}/{name}'] = os.path.join(directory, name)
    return entries


def variants(path):
    stem = os.path.splitext(os.path.basename(path))[0]
    directory = os.path.dirname(path)
    image = Image.open(path).convert('RGB')
    widths = sorted({w for w in (PAGE_WIDTH, image.width) if w <= image.width})
    written = 0
    total = 0

    for width in widths:
        if width == image.width:
            resized = image
        else:
            height = round(image.height * width / image.width)
            resized = image.resize((width, height), Image.LANCZOS)

        for extension, image_format, options in FORMATS:
            target = os.path.join(directory, f'{stem}-{width}.{extension}')
            resized.save(target, image_format, **options)
            total += os.path.getsize(target)
            written += 1

    # One pixel is the cheapest honest placeholder: it is the image's own
    # average colour, so the box behind a loading picture is already right.
    red, green, blue = image.resize((1, 1), Image.LANCZOS).getpixel((0, 0))
    return image.size, written, total, f'#{red:02x}{green:02x}{blue:02x}'


def write(sizes, colors):
    lines = [
        '/** Generated by `npm run images` — do not edit by hand. */',
        'export const imageSizes: Record<string, [number, number]> = {',
    ]
    for src in sorted(sizes):
        width, height = sizes[src]
        lines.append(f"  '{src}': [{width}, {height}],")
    lines.append('}')
    lines.append('')
    with open(SIZES, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))

    lines = [
        '/** Generated by `npm run images` — do not edit by hand. */',
        'export const imageColors: Record<string, string> = {',
    ]
    for src in sorted(colors):
        lines.append(f"  '{src}': '{colors[src]}',")
    lines.append('}')
    lines.append('')
    with open(COLORS, 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(lines))


def main():
    entries = collect()
    if not entries:
        sys.exit('no images found under public/projects or public/case')

    if not __import__('PIL.features', fromlist=['check']).check('avif'):
        sys.exit('this Pillow cannot write AVIF — upgrade it before regenerating')

    sizes = {}
    colors = {}
    files = 0
    total = 0
    for src, path in entries.items():
        size, written, size_bytes, color = variants(path)
        sizes[src] = size
        colors[src] = color
        files += written
        total += size_bytes

    write(sizes, colors)
    print(f'{len(entries)} sources -> {files} AVIF/WebP files, {total // 1024} KB total')
    print(f'wrote {os.path.relpath(SIZES, ROOT)} and {os.path.relpath(COLORS, ROOT)}')


if __name__ == '__main__':
    main()
